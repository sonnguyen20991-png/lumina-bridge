export function normalizeCountry(value) {
  if (value == null || (typeof value === 'string' && !value.trim())) return {value:null};
  if (typeof value !== 'string') return {error:'COUNTRY_REVIEW_REQUIRED'};
  const normalized = accepted.get(key(value));
  return normalized ? {value:normalized} : {error:'COUNTRY_REVIEW_REQUIRED'};
}
export function normalizeCountryFields(row) {
  const output = {...row};
  const changes = [];
  for (const field of ['contact_country','company_country']) {
    const result = normalizeCountry(row[field]);
    if (result.error) return {error:result.error,field};
    output[field] = result.value;
    if (result.value !== null && result.value !== row[field]) {
      changes.push({field,before:row[field],after:result.value});
    }
  }
  return {row:output,changes};
}
